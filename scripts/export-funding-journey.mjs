/** Reproduce the vector artwork module and both active posters from the saved
 * Higgsfield master and the authored timeline. No network or renderer required.
 * Run: node scripts/export-funding-journey.mjs
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const sha256 = value => createHash('sha256').update(value).digest('hex');
const artworkPath = 'src/artwork/funding-planning-master.svg';
const sourceSvg = await readFile(new URL(artworkPath, root), 'utf8');
// The saved vector source is deliberately restricted to this small vocabulary.
// It is converted to numeric geometry, never injected as external SVG markup.
if (/<(?:script|foreignObject|image|use|style|filter|animate|set)\b|\bon[a-z]+\s*=|(?:href|url\s*\()/i.test(sourceSvg)) throw new Error('Unexpected active/external SVG content');
const groupNames = ['construction', 'blueprint', 'alignment', 'floor', 'facade', 'roof', 'details'];
const groups = Object.fromEntries(groupNames.map(name => [name, []]));
const stack = [{ attrs: {}, opacity: 1, owner: null }];
const pick = (attrs, names) => Object.fromEntries(names.filter(name => attrs[name] != null).map(name => [name, attrs[name]]));
for (const token of sourceSvg.matchAll(/<\/?([a-zA-Z]+)\b([^>]*)>/g)) {
  const [raw, tag, tail] = token;
  const closing = raw.startsWith('</');
  if (tag === 'g' && closing) { stack.pop(); continue; }
  if (closing) continue;
  const own = Object.fromEntries([...tail.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]));
  if (Object.values(own).some(value => /[<>&]/.test(value))) throw new Error('SVG entities are outside the saved artwork format');
  if (tag === 'g') {
    const parent = stack.at(-1);
    const owner = own.id || parent.owner;
    if (owner && !groups[owner]) throw new Error(`Unexpected SVG group: ${owner}`);
    const attrs = { ...parent.attrs, ...pick(own, ['fill', 'stroke', 'stroke-width', 'fill-opacity', 'stroke-dasharray']) };
    stack.push({ attrs, owner, opacity: parent.opacity * Number(own.opacity ?? 1) });
  } else if (tag === 'path' || tag === 'ellipse') {
    const parent = stack.at(-1);
    if (!parent.owner) throw new Error('Every artwork shape must have a semantic group');
    const attrs = { ...parent.attrs, ...pick(own, ['d', 'cx', 'cy', 'rx', 'ry', 'transform', 'fill', 'stroke', 'stroke-width', 'fill-opacity', 'stroke-dasharray']) };
    if (attrs.fill === 'none') delete attrs.fill;
    if (attrs.stroke === '#101110') delete attrs.stroke;
    const opacity = parent.opacity * Number(own.opacity ?? 1);
    groups[parent.owner].push({ tag, attrs, opacity });
  } else if (!['svg', 'title', 'rect'].includes(tag)) throw new Error(`Unexpected SVG element: ${tag}`);
}
if (stack.length !== 1 || groupNames.some(name => !groups[name].length)) throw new Error('Incomplete saved artwork structure');
const artwork = {
  source: artworkPath, sourceSha256: sha256(sourceSvg), provider: 'Higgsfield', model: 'GPT Image 2.6',
  jobId: 'f1b1dc02-899c-42be-a98e-599cced4491f', estimatedCost: 1.5,
  groups,
};
await writeFile(new URL('src/funding-artwork.js', root), `/** Generated by scripts/export-funding-journey.mjs from the immutable SVG master. */\nexport const fundingArtwork = ${JSON.stringify(artwork, null, 2)};\n`);
const { fundingJourneySvg } = await import('../src/funding-journey.js');
const master = await readFile(new URL('src/funding-journey.js', root));
const exports = [
  ['public/images/funding-journey.svg', false, 1600, 900],
  ['public/images/funding-journey-mobile.svg', true, 800, 1000],
];
const assets = [];
for (const [path, portrait, width, height] of exports) {
  const body = `${fundingJourneySvg(portrait, true)}\n`;
  await writeFile(new URL(path, root), body);
  assets.push({ path, width, height, bytes: Buffer.byteLength(body), sha256: sha256(body) });
}
const output = new URL('outputs/cinematic-polish-20261110/funding/', root);
await mkdir(output, { recursive: true });
await writeFile(new URL('asset-manifest.json', output), `${JSON.stringify({
  master: 'src/funding-journey.js', masterSha256: sha256(master),
  recipe: 'node scripts/export-funding-journey.mjs',
  artwork: { source: artwork.source, sha256: artwork.sourceSha256, provider: artwork.provider, model: artwork.model, jobId: artwork.jobId, estimatedCost: artwork.estimatedCost,
    description: 'Higgsfield vector pavilion, blueprint and drafting tools; adapted into two authored scenes without people. Existing bulb and dossier retained.' },
  palette: { paper: '#dfff00', ink: '#101110' },
  motion: { seconds: 22, staticPoster: 'Complete overview, also used without JavaScript' },
  previous: 'Git history; original job SVG retained unchanged in outputs/cinematic-polish-20261110/higgsfield/',
  assets,
}, null, 2)}\n`);
console.log(JSON.stringify({ master: 'src/funding-journey.js', artworkShapes: Object.values(groups).reduce((sum, shapes) => sum + shapes.length, 0), assets }));
