/** Generate JSON-LD from the same catalog, prices and hours used by the UI.
 * --write updates only the generated block in the six HTML files.
 * --check fails if an HTML block is absent or stale. No arguments writes review
 * copies to artifacts/restoration-20261109/schema without changing the site.
 */
import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {OPENING_HOURS, HOURS_SOURCE} from '../src/opening-hours.js';
import {productUnitCents, GLOVO_URL, PICKUP_PHONE} from '../src/cart.js';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const pages = ['index.html','versione-a.html','versione-b.html','ordina.html','ordina-a.html','ordina-b.html'];
const begin = '<!-- Mr Smeet structured data: generated by scripts/build-structured-data.mjs -->';
const end = '<!-- /Mr Smeet structured data -->';
const blockPattern = /\s*<!-- Mr Smeet structured data: generated by scripts\/build-structured-data\.mjs -->[\s\S]*?<!-- \/Mr Smeet structured data -->/g;
const names = {menu:'Menù completi',burger:'Panini',fries:'Contorni'};
const days = {Mon:'Monday',Tue:'Tuesday',Wed:'Wednesday',Thu:'Thursday',Fri:'Friday',Sat:'Saturday',Sun:'Sunday'};
const time = minutes => `${String(Math.floor(minutes/60)).padStart(2,'0')}:${String(minutes%60).padStart(2,'0')}`;
const readJSON = async filename => JSON.parse(await readFile(path.join(root, filename),'utf8'));

export async function loadInputs() {
  const [business,products,presentation,media] = await Promise.all([
    readJSON('data/business.json'),readJSON('data/menu.json'),readJSON('data/menu-presentation.json'),readJSON('data/appetite-media.json'),
  ]);
  return {business,products,presentation,media};
}

export function openingHoursSchema(hours = OPENING_HOURS) {
  return Object.entries(days).flatMap(([short,day]) => {
    const slots = hours[short];
    assert.ok(Array.isArray(slots),`Missing hours for ${short}`);
    return (slots.length ? slots : [[0,0]]).map(([start,finish]) => ({
      '@type':'OpeningHoursSpecification',dayOfWeek:`https://schema.org/${day}`,
      opens:time(start),closes:time(finish),
    }));
  });
}

export function buildGraph({business,products,presentation,media}, {includeMenu = true} = {}) {
  const base = business.siteUrl;
  assert.ok(/^https:\/\/.+\/$/.test(base),'An absolute HTTPS site URL ending in / is required');
  const absolute = relative => new URL(relative,base).href;
  const restaurantId = `${base}#restaurant`;
  const restaurant = {
    '@type':'Restaurant','@id':restaurantId,name:business.name,url:base,
    image:absolute(business.image),logo:absolute(business.logo),telephone:PICKUP_PHONE,
    email:business.email,
    address:{'@type':'PostalAddress',streetAddress:business.streetAddress,addressLocality:business.addressLocality,addressCountry:business.addressCountry},
    servesCuisine:business.servesCuisine,
    sameAs:[business.officialUrl,business.instagram],
    openingHoursSpecification:openingHoursSchema(),
    hasMenu:includeMenu ? {'@id':`${base}#menu`} : `${base}#menu`,
  };
  if (!includeMenu) return {'@context':'https://schema.org','@graph':[restaurant]};
  const byId = new Map(products.map(item => [item.id,item]));
  const orderedIds = presentation.group_order.flatMap(group => presentation.product_order[group]);
  assert.equal(new Set(orderedIds).size,products.length,'Menu order must contain every product exactly once');
  assert.equal(orderedIds.length,products.length,'Menu must not duplicate products');
  const sections = presentation.group_order.map(group => ({
    '@type':'MenuSection','@id':`${base}#menu-section-${group}`,name:names[group],
    hasMenuItem:presentation.product_order[group].map(id => {
      const product = byId.get(id), photo = media[id];
      assert.ok(product && photo,`Missing product or image: ${id}`);
      const cents = productUnitCents(product);
      assert.ok(cents !== null,`Invalid catalog price: ${id}`);
      const item = {
        '@type':'MenuItem','@id':`${base}#menu-item-${id}`,name:product.name,
        description:product.description,image:absolute(photo.poster),
        offers:{'@type':'Offer',price:(cents/100).toFixed(2),priceCurrency:'EUR',url:GLOVO_URL,
          description:'Prezzo indicativo. Verifica promozioni e disponibilità sul canale scelto. Consegna ed eventuali commissioni sono escluse.'},
      };
      // Only the explicitly documented vegan recipe has a dietary claim.
      if (product.diet_label === 'Vegano') item.suitableForDiet = 'https://schema.org/VeganDiet';
      return item;
    }),
  }));
  return {'@context':'https://schema.org','@graph':[restaurant,{
    '@type':'Menu','@id':`${base}#menu`,name:'Il menù di Mr Smeet',url:`${base}#menu`,inLanguage:'it-IT',hasMenuSection:sections,
  }]};
}

export function injectStructuredData(html, graph) {
  assert.ok(/<\/head>/i.test(html),'HTML document has no closing head');
  const clean = html.replace(blockPattern,'');
  assert.ok(!/<script\b[^>]*type=["']application\/ld\+json["']/i.test(clean),'Unexpected existing JSON-LD: review before merging');
  // Escape HTML delimiters so catalog text cannot terminate the script element.
  const json = JSON.stringify(graph).replaceAll('<','\\u003c').replaceAll('>','\\u003e').replaceAll('&','\\u0026');
  return clean.replace(/\s*<\/head>/i,`\n  ${begin}\n  <script id="mrsmeet-structured-data" type="application/ld+json">${json}</script>\n  ${end}\n</head>`);
}

async function main() {
  const inputs = await loadInputs();
  const write = process.argv.includes('--write'), check = process.argv.includes('--check');
  assert.ok(!(write && check),'Choose --write or --check');
  const output = path.join(root,'artifacts/restoration-20261109/schema');
  if (!write && !check) await mkdir(output,{recursive:true});
  for (const page of pages) {
    const filename = path.join(root,page), html = await readFile(filename,'utf8');
    const graph = buildGraph(inputs,{includeMenu:!page.startsWith('ordina')});
    const next = injectStructuredData(html,graph);
    if (check) assert.equal(html,next,`${page}: structured data is missing or stale; run node scripts/build-structured-data.mjs --write`);
    else if (write) { if (next !== html) await writeFile(filename,next); }
    else {
      await writeFile(path.join(output,page),next);
      await writeFile(path.join(output,page.replace('.html','.json')),JSON.stringify(graph,null,2)+'\n');
    }
  }
  console.log(`${check?'Checked':write?'Updated':'Prepared review copies for'} ${pages.length} pages; 10 menu items in each homepage, hours source ${HOURS_SOURCE}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
